# ------------------------------------------------------------------ 请求构造

def test_request_url_carries_format_resulttype_pagesize_and_query(fake_get):
    calls = fake_get(_payload())
    _engine().search("hallucination rate of citations", max_results=7)
    parsed = urllib.parse.urlparse(calls[0])
    q = urllib.parse.parse_qs(parsed.query)
    assert parsed.scheme == 'https' and parsed.netloc == 'www.ebi.ac.uk'
    assert q['format'] == ['json'] and q['resultType'] == ['core']
    assert q['pageSize'] == ['7']
    assert q['query'] == ['hallucination rate of citations']


def test_pagesize_is_capped_at_the_api_limit(fake_get):
    """接口 pageSize 上限 1000，超了直接 400——不能把调用方给的数原样塞进去。"""
    calls = fake_get(_payload())
    _engine().search("test", max_results=5000)
    q = urllib.parse.parse_qs(urllib.parse.urlparse(calls[0]).query)
    assert int(q['pageSize'][0]) <= 1000


# ------------------------------------------------------------------ 失败与空结果分开

def test_http_failure_returns_none_not_empty_list(fake_get):
    """通道挂了必须回 None（断路器据此记失败）；实测本机对整条 rest/ 前缀 503。"""
    fake_get(None)
    assert _engine().search("hallucination") is None


def test_empty_result_list_returns_empty_list(fake_get):
    """hitCount=0 是「调通了但没命中」，不是故障——回 None 会把 0 命中报成引擎坏了。"""
    fake_get(_payload())
    assert _engine().search("一个不存在的词组") == []


def test_non_json_body_returns_none(fake_get):
    """网关页（503 的 HTML）不是 JSON：不能当成 0 命中静默放过。"""
    fake_get(b"<html><head><title>503 Service Temporarily Unavailable</title></head></html>")
    assert _engine().search("hallucination") is None
