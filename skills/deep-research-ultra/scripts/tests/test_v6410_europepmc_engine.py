def _payload(*items):
    return json.dumps({
        "version": "6.9", "hitCount": len(items),
        "nextCursorMark": "AoIIQL9jUig1NjMwOTE2MA==",
        "request": {"query": "test", "pageSize": "2",
                    "resultType": "core", "accept": "application/json"},
        "resultList": {"result": list(items)},
    }).encode("utf-8")


@pytest.fixture
def fake_get(monkeypatch):
    """把 _http_get 换成假件，记下发出去的 URL；返回什么由用例决定。"""
    calls = []

    def _install(body):
        def fake(url, **kwargs):
            calls.append(url)
            return body
        monkeypatch.setattr(ae, '_http_get', fake)
        return calls
    return _install


